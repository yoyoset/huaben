# 2026-10-02 生产:《杂役仙尊》第 1、2 章同名("扫地撞破私藏丹")——章纲没查重。这里把已有标题列给编辑。
def title_rule(titles: list[str] | None) -> str:
    if not titles:
        return ""
    shown = "、".join(titles[-40:])
    more = "…" if len(titles) > 40 else ""
    return (f"书名已有章节标题(新章标题不得与这些重复,也不要只改一两个字):{shown}{more}。")


